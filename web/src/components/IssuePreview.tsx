/** Reads and writes the whole card: one paused timeline, replayed by the Replay pill. */
function useIssueTimeline(
  wrapRef: React.RefObject<HTMLDivElement | null>,
  tlRef: React.MutableRefObject<gsap.core.Timeline | null>,
  reduced: boolean,
): void {
  useLayoutEffect(() => {
    if (reduced) return;
    const root = wrapRef.current;
    if (root === null) return;

    const q = <T extends HTMLElement = HTMLElement>(selector: string): T[] =>
      Array.from(root.querySelectorAll<T>(selector));

    const [typeEl] = q('[data-title-type]');
    // The markup lives in this file, so a missing node means there is nothing to animate.
    if (typeEl === undefined) return;

    const caret = q('[data-caret]');
    const animated = q('[data-anim]');

    // Blink and pulse live outside the timeline so restart() can drive them explicitly.
    const caretBlink = gsap.fromTo(
      caret,
      { opacity: 1 },
      { opacity: 0, duration: 0.42, repeat: -1, yoyo: true, ease: 'none', paused: true },
    );
    const dotPulse = gsap.to(q('[data-chip-dot]'), {
      opacity: 0.3,
      scale: 0.8,
      duration: 0.55,
      repeat: -1,
      yoyo: true,
      ease: 'sine.inOut',
      paused: true,
    });

    // Every element keeps its final box: only opacity and transform change, so nothing reflows.
    gsap.set([...q('[data-breadcrumb]'), ...q('[data-tab]')], { autoAlpha: 0 });
    gsap.set(q('[data-title-rest]'), { autoAlpha: 0 });
    gsap.set(caret, { autoAlpha: 0 });
    gsap.set(q('[data-open-pill]'), { autoAlpha: 0, scale: 0.6, transformOrigin: '0% 50%' });
    gsap.set(q('[data-issue-meta]'), { autoAlpha: 0 });
    gsap.set(q('[data-comment]'), { autoAlpha: 0, y: 12 });
    gsap.set(q('[data-sidebar]'), { autoAlpha: 0, y: 8 });
    gsap.set(q('[data-reveal]'), { autoAlpha: 0, y: 8 });
    gsap.set(q('[data-step]'), { autoAlpha: 0, y: 6 });
    gsap.set(q('[data-badge]'), { autoAlpha: 0, scale: 0.7, transformOrigin: '50% 50%' });
    gsap.set(q('[data-badge-glow]'), { opacity: 0, scale: 0.6, transformOrigin: '50% 50%' });
    gsap.set(q('[data-shot]'), { autoAlpha: 0, y: 6 });
    gsap.set(q('[data-label-pop]'), { autoAlpha: 0, scale: 0.8, transformOrigin: '50% 50%' });
    gsap.set(q('[data-chip-creating]'), { autoAlpha: 0, y: -4 });
    gsap.set(q('[data-chip-created]'), { autoAlpha: 0 });
    gsap.set(q('[data-ring]'), { opacity: 0 });

    const typed = { chars: 0 };

    const tl = gsap.timeline({
      paused: true,
      defaults: { ease: 'power2.out' },
      // Will-change is a hint for the GPU only while the entrance is running.
      onStart: () => {
        for (const el of animated) el.style.willChange = 'transform, opacity';
      },
      onComplete: () => {
        for (const el of animated) el.style.willChange = 'auto';
      },
    });

    tl.to([...q('[data-breadcrumb]'), ...q('[data-tab]')], { autoAlpha: 1, duration: 0.4, stagger: 0.05 }, 0)
      .to(q('[data-chip-creating]'), { autoAlpha: 1, y: 0, duration: 0.35 }, 0)
      .call(() => dotPulse.restart(), undefined, 0)
      .set(caret, { autoAlpha: 1 }, TYPE_START)
      .call(() => caretBlink.restart(), undefined, TYPE_START)
      .to(
        typed,
        {
          chars: TITLE.length,
          duration: TITLE.length * CHAR_S,
          ease: 'none',
          onStart: () => {
            typeEl.textContent = '';
          },
          onUpdate: () => {
            typeEl.textContent = TITLE.slice(0, Math.round(typed.chars));
          },
        },
        TYPE_START,
      )
      .call(
        () => {
          caretBlink.pause();
          gsap.set(caret, { autoAlpha: 0 });
        },
        undefined,
        TYPE_END,
      )
      .to(q('[data-title-rest]'), { autoAlpha: 1, duration: 0.3 }, TYPE_END)
      .to(q('[data-open-pill]'), { autoAlpha: 1, scale: 1, duration: 0.55, ease: 'back.out(1.7)' }, 1.8)
      .to(q('[data-issue-meta]'), { autoAlpha: 1, duration: 0.35 }, 2.05)
      .to(q('[data-comment]'), { autoAlpha: 1, y: 0, duration: 0.45 }, 2.3)
      .to(q('[data-sidebar]'), { autoAlpha: 1, y: 0, duration: 0.45 }, 2.45)
      // Seven comment sections, 250ms apart: 2.6s through 4.1s.
      .to(q('[data-reveal]'), { autoAlpha: 1, y: 0, duration: 0.35, stagger: 0.25 }, 2.6)
      .to(q('[data-step]'), { autoAlpha: 1, y: 0, duration: 0.25, stagger: 0.1 }, 3.1)
      .to(q('[data-badge]'), { autoAlpha: 1, scale: 1, duration: 0.45, ease: 'back.out(2)' }, 3.35)
      .to(q('[data-badge-glow]'), { opacity: 0.85, scale: 1.7, duration: 0.28, ease: 'power2.out' }, 3.45)
      .to(q('[data-badge-glow]'), { opacity: 0, duration: 0.5 }, 3.75)
      .to(q('[data-shot]'), { autoAlpha: 1, y: 0, duration: 0.35, stagger: 0.15 }, 3.6)
      .to(q('[data-label-pop]'), { autoAlpha: 1, scale: 1, duration: 0.35, stagger: 0.12, ease: 'back.out(1.8)' }, 4.5)
      .to(q('[data-chip-creating]'), { autoAlpha: 0, duration: 0.25 }, 4.5)
      .call(() => dotPulse.pause(), undefined, 4.6)
      .to(q('[data-chip-created]'), { autoAlpha: 1, duration: 0.3 }, 4.55)
      .to(q('[data-chip-created]'), { autoAlpha: 0, duration: 0.35 }, 5.35)
      .fromTo(q('[data-ring]'), { opacity: 0, scale: 0.99 }, { opacity: 0.9, duration: 0.3, ease: 'power1.out' }, 5.5)
      .to(q('[data-ring]'), { opacity: 0, duration: 0.5 }, 5.85);

    tlRef.current = tl;

    return () => {
      tl.kill();
      caretBlink.kill();
      dotPulse.kill();
      tlRef.current = null;
    };
  }, [reduced, tlRef, wrapRef]);

  useEffect(() => {
    if (reduced) return;
    const root = wrapRef.current;
    if (root === null) return;

    const play = (): void => {
      tlRef.current?.restart();
    };

    if (typeof IntersectionObserver === 'undefined') {
      play();
      return;
    }

    // 40% of the card in the viewport is the cue; the observer fires once and then goes away.
    const observer = new IntersectionObserver(
      ([entry]) => {
        if (entry === undefined || !entry.isIntersecting) return;
        observer.disconnect();
        play();
      },
      { threshold: 0.4 },
    );
    observer.observe(root);
    return () => observer.disconnect();
  }, [reduced, tlRef, wrapRef]);
}

